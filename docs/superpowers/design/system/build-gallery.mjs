// Builds gallery.html: one self-contained page that renders every component
// preview locally, so the system can be reviewed in a browser with no runtime,
// no server and no build step. Run: node build-gallery.mjs
import fs from 'node:fs';
import path from 'node:path';

const here = path.dirname(new URL(import.meta.url).pathname);
const comps = path.join(here, 'components');

const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;');
const read = (p) => fs.readFileSync(p, 'utf8');

const dirs = fs.readdirSync(comps)
  .filter((d) => fs.statSync(path.join(comps, d)).isDirectory())
  .filter((d) => fs.existsSync(path.join(comps, d, 'preview.html')))
  .sort();

const cards = dirs.map((name) => {
  const raw = read(path.join(comps, name, 'preview.html'));
  const marker = raw.split('\n')[0];
  const sub = /subtitle="([^"]*)"/.exec(marker)?.[1] ?? '';
  const group = /group="([^"]*)"/.exec(marker)?.[1] ?? 'Cover';
  // each preview owns "root"; give it its own so they can share one page
  const body = raw
    .replace(/^<!--[^\n]*-->\n/, '')
    .replaceAll('id="root"', `id="root-${name}"`)
    .replaceAll("getElementById('root')", `getElementById('root-${name}')`);
  return { name, group, sub, body };
});

const order = ['Cover', 'Foundations', 'States', 'Surfaces'];
cards.sort((a, b) => (order.indexOf(a.group) - order.indexOf(b.group)) || a.name.localeCompare(b.name));

const html = `<!doctype html>
<html lang="en" data-theme="light">
<head>
<meta charset="utf-8">
<title>Manifest design system</title>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Instrument+Sans:wght@400;500;600;700&family=IBM+Plex+Mono:wght@400;500&display=swap">
<script src="https://cdnjs.cloudflare.com/ajax/libs/react/18.3.1/umd/react.production.min.js"></script>
<script src="https://cdnjs.cloudflare.com/ajax/libs/react-dom/18.3.1/umd/react-dom.production.min.js"></script>
<script>
${read(path.join(comps, 'bundle.js'))}
</script>
<style>
${read(path.join(here, 'tokens.css'))}
${read(path.join(comps, 'bundle.css'))}
body { margin: 0; background: var(--surface-page); color: var(--ink); font-family: var(--font-sans); }
.g-wrap { max-width: 1040px; margin: 0 auto; padding: 48px 24px 96px; }
.g-lede { margin: 0 0 40px; font-size: 15px; line-height: 1.6; color: var(--ink-muted); max-width: 62ch; }
.g-group { margin: 40px 0 16px; font-size: 11px; font-weight: 600; letter-spacing: .1em; text-transform: uppercase; color: var(--ink-subtle); }
.g-card { background: var(--surface-card); border: 1px solid var(--border-default); border-radius: var(--radius-lg); overflow: hidden; margin-bottom: 16px; }
.g-head { padding: 14px 18px; border-bottom: 1px solid var(--border-subtle); display: flex; align-items: baseline; gap: 12px; }
.g-name { font-size: 15px; font-weight: 600; }
.g-sub { font-size: 13px; color: var(--ink-subtle); }
.g-body { overflow-x: auto; }
</style>
</head>
<body>
<div class="g-wrap">
  <h1 style="margin:0 0 12px; font-size:31px; font-weight:700; letter-spacing:-.03em;">Manifest design system</h1>
  <p class="g-lede">Every component, rendered from the same <code>bundle.js</code> a product would load.
  Generated by <code>build-gallery.mjs</code> — open this file in a browser, no server needed.
  Needs a network connection for React and the two typefaces.</p>
${cards.map((c, i) => `${i === 0 || c.group !== cards[i - 1].group ? `  <div class="g-group">${esc(c.group)}</div>\n` : ''}  <section class="g-card">
    <div class="g-head"><span class="g-name">${esc(c.name)}</span><span class="g-sub">${esc(c.sub)}</span></div>
    <div class="g-body">
${c.body.trimEnd()}
    </div>
  </section>`).join('\n')}
</div>
</body>
</html>
`;

fs.writeFileSync(path.join(here, 'gallery.html'), html);
console.log(`gallery.html: ${cards.length} previews, ${(html.length / 1024).toFixed(0)}KB`);
